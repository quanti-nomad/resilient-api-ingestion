"""End-to-end demo against the unreliable mock API.

    python demo.py            # full demo (about a minute): 6 months, 12 centers
    python demo.py --quick    # smaller dataset, a few seconds

1. starts the mock API with chaos turned on
2. backfill run: loads everything since the start date
3. simulates three days passing (bookings resolve, discounts post, new guests)
4. incremental run: loads only what changed
5. compares the database with the API's actual data, record by record
6. writes docs/demo_run.md
"""

from __future__ import annotations

import argparse
import shutil
import time
from datetime import date
from pathlib import Path

import requests
from sqlalchemy import create_engine

from ingest.client import ApiClient
from ingest.pipeline import RunSummary, Settings, run
from ingest.verify import compare, truth_from_dataset
from mock_api.data import Dataset
from mock_api.server import CLIENT_ID, CLIENT_SECRET, Chaos, serve

ROOT = Path(__file__).resolve().parent


def run_table(s: RunSummary) -> str:
    rows = "\n".join(
        f"| {e.endpoint} | {e.status} | {e.scope} | {e.pages} | {e.received:,} | {e.duplicates_dropped} | "
        f"{e.inserted:,} | {e.updated:,} | {e.unchanged:,} | {e.rejected} |"
        for e in s.endpoints
    )
    t = s.totals()
    return (
        "| Endpoint | Status | Scope | Pages | Received | Duplicates dropped | Inserted | Updated | Unchanged | Rejected |\n"
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n" + rows +
        f"\n\nSurvived: **{t.requests:,} requests**, {t.rate_limited} rate limits (429), "
        f"{t.server_errors} server errors (5xx), {t.timeouts} timeouts, {t.token_refreshes} token refreshes, "
        f"{t.retries} retries.\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true")
    a = ap.parse_args()

    if a.quick:
        ds = Dataset(date(2026, 1, 1), date(2026, 2, 28), n_centers=4, n_guests=500, drift_from=date(2026, 2, 15))
        chaos = Chaos(rate_limit_per_sec=40, retry_after_seconds=0.2, error_rate=0.08, timeout_rate=0.02,
                      timeout_seconds=0.6, page_overlap_rate=0.1, token_ttl_seconds=2, advertised_ttl_seconds=3)
        client_kw = dict(rate_per_sec=50, timeout=0.3, backoff_base=0.05)
    else:
        ds = Dataset(date(2026, 1, 1), date(2026, 6, 27), drift_from=date(2026, 5, 1))
        chaos = Chaos(rate_limit_per_sec=12, retry_after_seconds=1, error_rate=0.05, timeout_rate=0.02,
                      timeout_seconds=3, page_overlap_rate=0.05, token_ttl_seconds=20, advertised_ttl_seconds=30)
        client_kw = dict(rate_per_sec=15, timeout=2, backoff_base=0.5)

    workdir = ROOT / "data" / "demo"
    shutil.rmtree(workdir, ignore_errors=True)
    workdir.mkdir(parents=True)
    server, api, url = serve(ds, chaos)
    settings = Settings(url, CLIENT_ID, CLIENT_SECRET, db_url=f"sqlite:///{workdir}/ingest.db",
                        landing_dir=str(workdir / "landing"), backfill_start=ds.start, **{
                            k: v for k, v in client_kw.items() if k in ("rate_per_sec", "timeout")})
    client = ApiClient(url, CLIENT_ID, CLIENT_SECRET, **client_kw)
    engine = create_engine(settings.db_url)

    print(f"Mock API at {url} with chaos: {chaos}")
    t0 = time.time()
    backfill = run(settings, as_of=ds.clock, client=client)
    t1 = time.time()
    after_backfill = compare(engine, truth_from_dataset(ds))
    print(f"Backfill: {t1 - t0:.1f}s, ok={backfill.ok}")

    changes = requests.post(url + "/admin/advance?days=3").json()
    print(f"Three days pass: {changes}")
    t2 = time.time()
    incremental = run(settings, as_of=ds.clock, client=client)
    t3 = time.time()
    after_incremental = compare(engine, truth_from_dataset(ds))
    print(f"Incremental: {t3 - t2:.1f}s, ok={incremental.ok}")
    server.shutdown()

    def verify_table(rep):
        return ("| Endpoint | In the API | Landed | Missing | Extra | Mismatched |\n| --- | --- | --- | --- | --- | --- |\n" +
                "\n".join(f"| {k} | {v['expected']:,} | {v['landed']:,} | {v['missing']} | {v['extra']} | {v['mismatched']} |"
                          for k, v in rep.items()))

    exact = all(v["missing"] == v["extra"] == v["mismatched"] == 0 for v in after_incremental.values())
    checks = "\n".join(f"| {c.name} | {c.status} | {c.detail} |" for c in incremental.checks)
    report = f"""# Demo run

*Generated by `python demo.py{' --quick' if a.quick else ''}`. Synthetic data; mock API with chaos turned on.*

Chaos settings: {chaos.rate_limit_per_sec:g} requests/second limit, {chaos.error_rate:.0%} server errors,
{chaos.timeout_rate:.0%} slow responses ({chaos.timeout_seconds:g}s against a {client_kw['timeout']:g}s client timeout),
{chaos.page_overlap_rate:.0%} overlapping pages, tokens expiring after {chaos.token_ttl_seconds:g}s while advertising
{chaos.advertised_ttl_seconds:g}s, 7-day maximum date range, and a new field (`booking_channel`) appearing mid-history.

## 1. Backfill ({t1 - t0:.0f}s)

{run_table(backfill)}
{verify_table(after_backfill)}

## 2. Three days pass

{changes['resolved']} bookings resolved (completed, cancelled or no-show), {changes['adjusted']} completed visits
discounted after the fact, {changes['new_appointments']} new bookings, {changes['new_guests']} new guests.

## 3. Incremental run ({t3 - t2:.0f}s)

{run_table(incremental)}
{verify_table(after_incremental)}

**Database matches the API exactly: {"yes" if exact else "NO"}.**

## Post-load checks

| Check | Status | Detail |
| --- | --- | --- |
{checks}

## Alerts raised

{chr(10).join('- ' + x for x in backfill.alerts + incremental.alerts) or '- none'}
"""
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/demo_run.md").write_text(report)
    print(f"\nExact match with the API: {exact}. Report: docs/demo_run.md")


if __name__ == "__main__":
    main()
